export const STRINGS = { en, ar };
const KEY = 'dcr.lang';

let lang = 'en';
try { lang = localStorage.getItem(KEY) === 'ar' ? 'ar' : 'en'; } catch { /* storage blocked */ }

export function getLang() {
  return lang;
}

export function t(key, vars = {}, forceLang) {
  const dict = STRINGS[forceLang ?? lang];
  let s = dict[key] ?? en[key] ?? key;
  for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
  return s;
}

export function applyI18n(root = document) {
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
  root.querySelectorAll('[data-i18n]').forEach((n) => { n.textContent = t(n.dataset.i18n); });
  root.querySelectorAll('[data-i18n-ph]').forEach((n) => { n.placeholder = t(n.dataset.i18nPh); });
  root.querySelectorAll('[data-i18n-title]').forEach((n) => { n.title = t(n.dataset.i18nTitle); });
  root.querySelectorAll('[data-i18n-aria]').forEach((n) => { n.setAttribute('aria-label', t(n.dataset.i18nAria)); });
}

export function setLang(next) {
  lang = next === 'ar' ? 'ar' : 'en';
  try { localStorage.setItem(KEY, lang); } catch { /* ignore */ }
  applyI18n();
  window.dispatchEvent(new CustomEvent('langchange', { detail: lang }));
}

/** Wires an `EN | ع` toggle button. */
export function bindLangToggle(button) {
  const render = () => {
    button.innerHTML = `<span class="${lang === 'en' ? 'on' : ''}">EN</span><span class="sep">|</span><span class="${lang === 'ar' ? 'on' : ''}" lang="ar">ع</span>`;
    button.setAttribute('aria-label', t('lang.toggle'));
  };
  button.addEventListener('click', () => { setLang(lang === 'en' ? 'ar' : 'en'); render(); });
  render();
}
